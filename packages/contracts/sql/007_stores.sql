-- Stores (ADR 015): an admin creates an extra WooCommerce store; the gateway provisions it in its own
-- namespace `store-<slug>` (MariaDB, WordPress, bootstrap Job, woo-mcp, NetworkPolicies, quota) and
-- registers the store's woo-mcp as the upstream `<slug>` once it is ready. Additive only: the
-- previous gateway image ignores the new table and column (a store's upstream row then looks like a
-- disabled or ordinary in-cluster upstream to it).

-- Upstream rows created for stores. Managed through /api/stores only (the upstream PATCH/DELETE
-- routes refuse them); the SSRF guard allows exactly woo-mcp.store-<slug>.svc.cluster.local for
-- them at call time. The credential column holds the store's woo-mcp shared secret (sealed, as for
-- any upstream), which the gateway also writes into the store namespace's Secret.
ALTER TABLE upstreams ADD COLUMN store boolean NOT NULL DEFAULT false;
ALTER TABLE upstreams ADD CONSTRAINT upstreams_hosted_or_store CHECK (NOT (hosted AND store));

-- One row per store; id = its upstream row's id (1:1, deleted with it). No password is stored: the
-- database and WordPress admin passwords are generated by the gateway, written once into Secrets in
-- the store's namespace and never read back; the Application Password is created in-cluster by the
-- bootstrap Job. desired_state 'absent' = delete requested: the provisioner deletes the namespace
-- (PVCs included), waits until it is gone, then removes the permission rules and the upstream row
-- (which cascades here). generation is bumped by Retry (a new bootstrap Job).
CREATE TABLE stores (
  id                   uuid PRIMARY KEY REFERENCES upstreams ON DELETE CASCADE,
  admin_email          text NOT NULL CHECK (length(admin_email) BETWEEN 3 AND 254),
  desired_state        text NOT NULL DEFAULT 'present' CHECK (desired_state IN ('present', 'absent')),
  phase                text NOT NULL DEFAULT 'provisioning'
                       CHECK (phase IN ('provisioning', 'ready', 'failed', 'deleting')),
  reason               text CHECK (length(reason) <= 300),
  generation           integer NOT NULL DEFAULT 1 CHECK (generation BETWEEN 1 AND 1000),
  provision_started_at timestamptz NOT NULL DEFAULT now(),
  created_by           uuid REFERENCES users ON DELETE SET NULL,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  last_reconciled_at   timestamptz
);
